-- ============================================================
-- V4: раздача игроков по голосовым каналам и подмена ников
--
-- При старте игры бот меняет ник участника на его Steam-ник
-- (players.steam_name из /bind) и раскидывает игроков по двум
-- голосовым каналам по командам. После матча ник возвращается,
-- поэтому исходный ник сохраняем здесь.
--
-- Храним именно исходный ник (то, что было до подмены), а не
-- применённый: применённый всегда известен — это steam_name.
--
-- nickname_saved нужен отдельным флагом, а не проверкой на NULL:
-- исходный ник может быть законно null (у игрока не было ника на
-- сервере), и тогда по одному NULL нельзя отличить «не сохраняли» от
-- «сохранили пустое».
-- ============================================================

ALTER TABLE players_match ADD COLUMN original_nickname TEXT;
ALTER TABLE players_match
    ADD COLUMN nickname_saved BOOLEAN NOT NULL DEFAULT FALSE;